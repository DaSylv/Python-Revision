direction = input("In which direction should I go?")
if direction == "right":
    print("Robot will go to the right")

elif direction == "left":
    print("Robot will go to the left")

elif direction == "down":
    print("Robot will go to the down")

elif direction == "up":
    print("The robot will go to the up")

else :
    print("I do not know where to go...")

print("Game on...")
