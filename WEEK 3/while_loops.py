#We ask the user and save the number
total_apples_to_remove = int(input("How many apples should I remove?"))

#Cream o variabila care urmareste nr de mere
removed_apples = 0

#we use a while loop
while removed_apples < total_apples_to_remove:
    #we show the message
    print("Removed apple")

    #marim variabila cu 1
    removed_apples = removed_apples + 1